-- 1) Tabelas
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text,
  is_admin boolean not null default false
);

create table if not exists public.mangas (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null default 'Autor desconhecido',
  cat text not null default 'Shonen',
  price numeric(10,2) not null check (price > 0),
  stock int not null default 0 check (stock >= 0),
  hue int not null default 200,
  img text not null default ''
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  user_email text,
  items jsonb not null,
  total numeric(10,2) not null,
  status text not null default 'Pendente',
  created_at timestamptz not null default now()
);

-- 2) Cria o perfil automaticamente quando alguém se cadastra
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, name)
  values (new.id, coalesce(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)));
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 3) Função que diz se quem está logado é admin
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false)
$$;

-- 4) Segurança (RLS): cada pessoa só vê e faz o que pode
alter table public.profiles enable row level security;
alter table public.mangas   enable row level security;
alter table public.orders   enable row level security;

drop policy if exists "ver perfil" on public.profiles;
create policy "ver perfil" on public.profiles for select
  using (id = auth.uid() or public.is_admin());

drop policy if exists "ver produtos" on public.mangas;
create policy "ver produtos" on public.mangas for select using (true);

drop policy if exists "admin cria produtos" on public.mangas;
create policy "admin cria produtos" on public.mangas for insert with check (public.is_admin());

drop policy if exists "admin edita produtos" on public.mangas;
create policy "admin edita produtos" on public.mangas for update
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admin exclui produtos" on public.mangas;
create policy "admin exclui produtos" on public.mangas for delete using (public.is_admin());

drop policy if exists "ver pedidos" on public.orders;
create policy "ver pedidos" on public.orders for select
  using (user_id = auth.uid() or public.is_admin());

drop policy if exists "admin atualiza pedidos" on public.orders;
create policy "admin atualiza pedidos" on public.orders for update
  using (public.is_admin()) with check (public.is_admin());

-- 5) Finalizar compra: confere estoque, desconta e cria o pedido, tudo de forma segura
create or replace function public.place_order(p_items jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  it record; m public.mangas; v_qty int; v_total numeric := 0;
  v_items jsonb := '[]'::jsonb; v_id bigint;
begin
  if auth.uid() is null then raise exception 'Entre na sua conta para comprar'; end if;
  if jsonb_array_length(p_items) = 0 then raise exception 'Carrinho vazio'; end if;
  for it in select value from jsonb_array_elements(p_items) loop
    v_qty := (it.value->>'qty')::int;
    select * into m from public.mangas where id = (it.value->>'id')::bigint for update;
    if not found then raise exception 'Produto não encontrado'; end if;
    if v_qty < 1 or m.stock < v_qty then raise exception 'Estoque insuficiente: %', m.title; end if;
    update public.mangas set stock = stock - v_qty where id = m.id;
    v_total := v_total + m.price * v_qty;
    v_items := v_items || jsonb_build_array(
      jsonb_build_object('title', m.title, 'qty', v_qty, 'price', m.price));
  end loop;
  insert into public.orders (user_id, user_email, items, total)
  values (auth.uid(), auth.jwt() ->> 'email', v_items, v_total)
  returning id into v_id;
  return v_id;
end $$;

revoke execute on function public.place_order(jsonb) from public, anon;
grant  execute on function public.place_order(jsonb) to authenticated;

